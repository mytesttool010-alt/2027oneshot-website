const getLink = (bvid) => `https://www.bilibili.com/video/${bvid}/`;
const programList = document.querySelector('[data-program-list]');
const backgrounds = [...document.querySelectorAll('[data-background-layer]')];
let activeBackground = 0;

function updateBackground(cover) {
  const next = (activeBackground + 1) % backgrounds.length;
  backgrounds[next].style.backgroundImage = `url("${cover}")`;
  backgrounds[next].classList.add('is-active');
  backgrounds[activeBackground].classList.remove('is-active');
  activeBackground = next;
}

function render(year) {
  const item = archives[year];
  document.querySelectorAll('.year-tab').forEach((button) => button.setAttribute('aria-selected', String(button.dataset.year === year)));
  document.querySelector('[data-year-label]').textContent = `${year} 拜年纪`;
  document.querySelector('[data-title]').textContent = item.title;
  document.querySelector('[data-description]').textContent = item.description;
  document.querySelector('[data-program-heading]').textContent = `${year} 节目单`;
  document.querySelector('[data-program-count]').textContent = item.programs.length ? `收录 ${item.programs.length} 个节目` : '节目单待补充';
  const player = document.querySelector('[data-player]');
  const playerPlaceholder = document.querySelector('[data-player-placeholder]');
  const link = document.querySelector('[data-bilibili-link]');
  if (item.bvid) {
    player.src = `https://player.bilibili.com/player.html?bvid=${item.bvid}&page=1&high_quality=1&danmaku=0`;
    player.hidden = false;
    player.style.display = '';
    playerPlaceholder.hidden = true;
    playerPlaceholder.style.display = '';
    link.href = getLink(item.bvid);
    link.hidden = false;
  } else {
    player.src = 'about:blank';
    player.hidden = true;
    player.style.display = 'none';
    playerPlaceholder.hidden = false;
    playerPlaceholder.style.display = 'grid';
    link.hidden = true;
  }
  programList.innerHTML = item.programs.length ? item.programs.map(([name, creator]) => `<article class="glass-card p-5"><p class="text-base font-bold leading-7 text-white">${name}</p><p class="mt-3 text-sm text-lamp">${creator}</p></article>`).join('') : '<div class="glass-card col-span-full px-6 py-12 text-center text-slate-300">节目单正在整理中，敬请期待。</div>';
  const credits = document.querySelector('[data-credits]');
  const creditsSection = document.querySelector('[data-credits-section]');
  creditsSection.hidden = !item.credits.length;
  credits.innerHTML = item.credits.map(([role, name]) => `<p><span class="block text-xs text-slate-500">${role}</span><span class="text-slate-200">${name}</span></p>`).join('');
  updateBackground(item.cover);
}

document.querySelectorAll('.year-tab').forEach((button) => button.addEventListener('click', () => render(button.dataset.year)));
render('2023');
